defmodule TemplateAppWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :template_app

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_template_app_key",
    signing_salt: "O9miAQI7",
    same_site: "Lax"
  ]

  socket("/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]
  )

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug(Plug.Static,
    at: "/",
    from: :template_app,
    gzip: not code_reloading?,
    only: TemplateAppWeb.static_paths()
  )

  if Application.compile_env(:template_app, :dev_routes, false) and Code.ensure_loaded?(Tidewave) do
    plug(Tidewave)
  end

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket("/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket)
    plug(Phoenix.LiveReloader)
    plug(Phoenix.CodeReloader)
    plug(AshPhoenix.Plug.CheckCodegenStatus)
    plug(Phoenix.Ecto.CheckRepoStatus, otp_app: :template_app)
  end

  plug(Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"
  )

  plug(Plug.RequestId)

  plug(CORSPlug,
    origin: &__MODULE__.cors_origins/1,
    methods: ["GET", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"],
    headers: ["Authorization", "Content-Type", "Accept"],
    expose: [],
    credentials: true,
    max_age: 86_400
  )

  plug(Plug.Telemetry, event_prefix: [:phoenix, :endpoint])

  plug(Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    length: 16_384,
    json_decoder: Phoenix.json_library()
  )

  plug(Plug.MethodOverride)
  plug(Plug.Head)
  plug(Plug.Session, @session_options)

  # Security headers
  plug(:put_security_headers)

  plug(TemplateAppWeb.Router)

  # Security headers function
  @doc false
  def cors_origins(_conn), do: Application.get_env(:cors_plug, :origin, [])

  defp put_security_headers(conn, _) do
    conn
    |> put_hsts_header()
    |> Plug.Conn.put_resp_header("x-frame-options", "DENY")
    |> Plug.Conn.put_resp_header("x-content-type-options", "nosniff")
    |> Plug.Conn.put_resp_header("x-xss-protection", "1; mode=block")
    |> Plug.Conn.put_resp_header("referrer-policy", "strict-origin-when-cross-origin")
    |> Plug.Conn.put_resp_header("x-permitted-cross-domain-policies", "none")
    |> Plug.Conn.put_resp_header("x-download-options", "noopen")
    |> put_csp_header()
  end

  defp put_hsts_header(conn) do
    if Application.get_env(:template_app, :env) == :prod and conn.scheme == :https do
      Plug.Conn.put_resp_header(
        conn,
        "strict-transport-security",
        "max-age=31536000; includeSubDomains; preload"
      )
    else
      conn
    end
  end

  defp put_csp_header(conn) do
    csp_policy =
      if Application.get_env(:template_app, :env) == :prod do
        "default-src 'self'; " <>
          "script-src 'self'; " <>
          "style-src 'self'; " <>
          "img-src 'self' data: https:; " <>
          "font-src 'self' data:; " <>
          "connect-src #{connect_src_policy()}; " <>
          "object-src 'none'; " <>
          "frame-ancestors 'none'; " <>
          "base-uri 'self'; " <>
          "form-action 'self';"
      else
        # Development CSP allows unsafe-inline and unsafe-eval for hot reloading
        "default-src 'self'; " <>
          "script-src 'self' 'unsafe-inline' 'unsafe-eval' https://cdnjs.cloudflare.com; " <>
          "style-src 'self' 'unsafe-inline' https://cdnjs.cloudflare.com; " <>
          "img-src 'self' data: https:; " <>
          "font-src 'self' data:; " <>
          "connect-src 'self' ws: wss:; " <>
          "frame-ancestors 'none';"
      end

    Plug.Conn.put_resp_header(conn, "content-security-policy", csp_policy)
  end

  defp connect_src_policy do
    ["'self'", Application.get_env(:template_app, :api_origin)]
    |> Enum.reject(&is_nil/1)
    |> Enum.join(" ")
  end
end
